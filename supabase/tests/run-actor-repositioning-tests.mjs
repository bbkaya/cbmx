// In-memory PostgreSQL only: no hosted client, env files or database URLs.
// Run with --pglite-module=/absolute/path/to/@electric-sql/pglite/dist/index.js.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { createServer } from 'vite';
import { fixture } from '../../review/cbmx/fixtures.js';
const flag = process.argv.find(arg => arg.startsWith('--pglite-module='));
const { PGlite } = await import(flag ? pathToFileURL(flag.slice('--pglite-module='.length)).href : '@electric-sql/pglite');
const db = new PGlite();
const server = await createServer({ configFile: false, envFile: false,
  server: { middlewareMode: true, hmr: false, ws: false, watch: null }, optimizeDeps: { noDiscovery: true, include: [] } });
const { moveActor } = await server.ssrLoadModule('/src/components/cbmx/cbmxMutators.ts');
const owner = '00000000-0000-0000-0000-000000000001', editor = '00000000-0000-0000-0000-000000000002', viewer = '00000000-0000-0000-0000-000000000003';
const bp = '10000000-0000-0000-0000-000000000001', pcb = '20000000-0000-0000-0000-000000000001';
const read = name => readFile(new URL(name, import.meta.url), 'utf8');
const rows = async (sql, params = []) => (await db.query(sql, params)).rows;
const caller = async user => { await db.exec('reset role; set role authenticated'); await db.query("select set_config('request.jwt.claim.sub', $1, false)", [user]); };
const save = async (version, blueprint) => (await rows('select * from public.save_blueprint_with_version($1,$2,$3,$4)', [bp, version, blueprint.meta.name, blueprint]))[0];
const load = async () => (await rows('select blueprint_json from blueprints where id=$1', [bp]))[0].blueprint_json;
let checks = 0;
const pass = label => { checks++; console.log('ok - ' + label); };
try {
  console.log((await rows('select version() as version'))[0].version);
  await db.exec(await read('fixtures/minimal-schema.sql'));
  await db.exec(await read('fixtures/process-links.sql'));
  await db.exec(await read('fixtures/process-link-functions.sql'));
  await db.exec(`create trigger bump_version before update on public.blueprints for each row execute function public.bump_version_and_updated_at();
    revoke all on function public.save_blueprint_with_version(uuid,bigint,text,jsonb) from public, anon;
    grant execute on function public.save_blueprint_with_version(uuid,bigint,text,jsonb) to authenticated;`);
  await db.exec(await read('../migrations/20261114091941_safe_cbmx_process_deletion.sql'));
  await db.query('insert into auth.users(id,created_at) values ($1,now()),($2,now()),($3,now())', [owner, editor, viewer]);
  const original = fixture(5, 'dense'); original.actors[3].type = original.actors[4].type = 'Customer';
  await caller(owner);
  await db.query('insert into blueprints(id,owner_user_id,name,blueprint_json) values ($1,$2,$3,$4)', [bp, owner, original.meta.name, original]);
  await db.exec('reset role');
  await db.query("insert into blueprint_members values ($1,$2,'owner'),($1,$3,'editor'),($1,$4,'viewer')", [bp, owner, editor, viewer]);
  await db.query("insert into process_canvas_blueprints(id,owner_user_id,name,blueprint_json) values ($1,$2,'Canvas',$3)", [pcb, owner, { contents: 'unchanged' }]);
  await db.query("insert into cbmx_process_links(cbmx_blueprint_id,cbmx_process_id,process_canvas_blueprint_id) values ($1,'P1',$2)", [bp, pcb]);
  const linksBefore = await rows('select * from cbmx_process_links'), pcbBefore = await rows('select * from process_canvas_blueprints');
  const moved = structuredClone(original); moveActor(moved, 'A5', 'left'); moveActor(moved, 'A5', 'left');
  await caller(owner); const saved = await save(1, moved);
  assert.equal(saved.ok, true); assert.equal(saved.version_no, 2); assert.deepEqual(saved.blueprint_json, moved); assert.deepEqual(await load(), moved);
  assert.deepEqual(saved.blueprint_json.actors.map(a => a.id), ['A1', 'A2', 'A5', 'A3', 'A4']);
  assert.deepEqual(saved.blueprint_json.coCreationProcesses, original.coCreationProcesses);
  pass('owner saves repeated moves and reopens exact JSON with all IDs, actor attributes and participant references retained');
  const edited = structuredClone(moved); moveActor(edited, 'A5', 'right');
  await caller(editor); const editorSave = await save(2, edited);
  assert.equal(editorSave.ok, true); assert.equal(editorSave.version_no, 3); assert.deepEqual(await load(), edited);
  pass('authorized collaborative editor persists a movement without role grouping');
  const unrelated = structuredClone(edited); unrelated.serviceScenario = 'Concurrent unrelated change';
  await caller(owner); assert.equal((await save(3, unrelated)).ok, true);
  const staleMove = structuredClone(edited); moveActor(staleMove, 'A4', 'left');
  await caller(editor); const stale = await save(3, staleMove);
  assert.equal(stale.ok, false); assert.equal(stale.reason, 'stale'); assert.deepEqual(await load(), unrelated);
  pass('concurrent movement cannot overwrite unrelated content saved at a newer version');
  const further = structuredClone(unrelated); moveActor(further, 'A4', 'left');
  assert.equal((await save(4, further)).ok, true); assert.deepEqual(await load(), further);
  pass('reloaded editor can move an actor while retaining the unrelated change');
  await caller(viewer); assert.deepEqual(await load(), further);
  const denied = await save(5, original); assert.equal(denied.ok, false); assert.equal(denied.reason, 'forbidden'); assert.deepEqual(await load(), further);
  pass('viewer reads reordered blueprint but cannot save movements');
  await db.exec('reset role'); assert.deepEqual(await rows('select * from cbmx_process_links'), linksBefore); assert.deepEqual(await rows('select * from process_canvas_blueprints'), pcbBefore);
  pass('all moves leave Process Canvas associations and contents unchanged');
  await caller(owner);
  const deleted = (await rows('select * from public.delete_cbmx_process_with_version($1,5,$2,$3,$4,null)', [bp, further.meta.name, further, 'P2']))[0];
  assert.equal(deleted.ok, true); assert.equal(deleted.version_no, 6); assert.deepEqual(deleted.blueprint_json.actors, further.actors);
  assert.deepEqual(deleted.blueprint_json.coCreationProcesses.map(p => p.id), ['P1', 'P3']); assert.deepEqual(await load(), deleted.blueprint_json);
  pass('existing versioned process deletion preserves reordered actors and retained process links');
  console.log(`${checks} checks passed. Incomplete disposable fixture only; hosted schema and records were not accessed.`);
} finally { await server.close(); await db.close(); }
